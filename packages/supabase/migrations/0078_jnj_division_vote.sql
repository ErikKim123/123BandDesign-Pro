-- 0078: J&J 부문별 관객투표 링크.
-- 참가 신청(0077)과 짝을 이루는 두 번째 링크 — 참가자는 신청하고, 관객은 투표한다.
-- 링크가 있으면 고객몰 대회 개요에 '관객투표' 섹션이 뜨고, 없으면 섹션 자체가 안 보인다.
-- 투표도 회원만 — 버튼은 로그인 상태에서만 링크로 이어진다(화면에서 처리).
-- 신청과 달리 대회가 시작돼도 닫지 않는다: 관객투표는 대회가 진행되는 동안 열리는 것이라
-- 운영자가 링크를 지우는 시점이 곧 마감이다.
-- idempotent.

alter table jnj_divisions
  add column if not exists vote_url text;

comment on column jnj_divisions.vote_url is
  '부문 관객투표 링크(구글폼·투표 페이지 등). 비면 고객몰에 관객투표 섹션이 안 뜬다.';
