-- 0084: J&J 결승 채점 항목 점수(심사위원 × 항목) 스냅샷.
--
-- 0074 는 결승을 '순위 + 총점 + 평균' 세 숫자로만 남긴다. 그런데 총점이 어떻게 나왔는지는
-- 그 세 숫자로 되짚을 수 없다 — 어느 항목에서 갈렸는지, 어느 심사위원이 어떻게 봤는지가
-- J&J Dash 안에만 있고 고객몰에서는 보이지 않았다. 그 표를 그대로 한 칸에 담는다.
--
-- 모양(J&J Dash 의 결승 채점 화면과 같은 배치):
--   { "items":  ["fundamentals", "connection", "musicality", "creativity"],
--     "judges": [ { "scores": [6, 9, 9, 10] }, ... ] }
--   · items  : 그 대회의 채점 항목 코드(contests.scoring_items) 순서. 대회마다 다르다.
--   · scores : items 와 같은 순서·같은 길이. 안 매긴 항목은 null.
--   · 심사위원 이름은 담지 않는다 — 이 테이블은 RLS 로 공개 읽기라 이름을 적는 순간
--     '누가 누구에게 몇 점' 이 공개 API 가 된다. 줄 순서만 심사석 순번을 따르고,
--     화면에서는 '심사위원 1·2·3' 으로 부른다.
--
-- 별도 테이블(성적 1줄 × 심사위원 N줄)로 안 쪼갠 이유: 이 값은 대회가 끝난 뒤 한 번 들어와
-- 다시 안 바뀌는 스냅샷이고, 읽을 때도 언제나 '그 한 줄과 통째로' 필요하다. 조인 하나를
-- 아끼는 것보다, 성적 1줄이 자기 근거를 안고 다니는 편이 가져오기·덮어쓰기에서 어긋날 일이 없다.
-- idempotent.

alter table jnj_scores
  add column if not exists criteria jsonb;

comment on column jnj_scores.criteria is
  'J&J Dash 결승 채점 항목 점수 스냅샷 — {items:[항목코드], judges:[{scores:[항목순 점수]}]}. 심사위원 이름은 넣지 않는다(공개 읽기 테이블). 고객몰 전체 결과 표에서 결승 줄을 누르면 펼쳐진다. 예선·본선은 null.';
