-- 0072: 스위처 4채널 프리뷰 — 카메라마다 '브라우저가 재생할 수 있는 주소'를 하나 둔다.
--
-- 배경: 폰 → OBS 는 SRT 이고, 그 신호는 현장 랜에서 OBS 로만 간다. 브라우저는 SRT 를 재생하지
--   못하고 123Band 서버에는 영상이 도달하지도 않는다. 그래서 스위처 안에서 4앵글을 눈으로 보려면
--   앵글마다 '웹에서 열리는 주소'가 따로 하나씩 있어야 한다.
--
-- 형식을 강제하지 않는다. 현장 사정에 따라 어느 쪽이든 들어올 수 있기 때문이다:
--   · 유튜브 라이브 (앵글마다 1개)  · HLS(.m3u8)  · MJPEG 스냅샷  · mp4/webm
--   판별은 화면에서 주소 모양으로 한다(packages/shared 의 미디어 판별과 같은 규칙).
--
-- 비워 두면 그 칸은 '프리뷰 주소 없음'으로 남는다. 스위칭·탈리·브리지는 이 값과 무관하게
-- 지금과 똑같이 동작한다 — 프리뷰는 어디까지나 감독의 눈을 돕는 부가 기능이다.
alter table live_cameras add column if not exists preview_url text;

comment on column live_cameras.preview_url is
  '스위처 프리뷰 재생 주소(유튜브 라이브/HLS/MJPEG/mp4). 비면 프리뷰 없음. 송출 경로와는 무관하다.';
